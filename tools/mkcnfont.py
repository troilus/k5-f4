#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build app/cn_font.c from the FontTool 8x8 dot-matrix file.

Ported from the UV-K1 LBJRadio `ENABLE_CN_FONT_EMBED` build
(App/ui/cn_font.c + tools/mkcnfont.py): the firmware carries only the
characters it actually draws, so Chinese works with no external font flash
(the classic UV-K5 has none).

Source of the bitmaps: UV-K1_FontTool_v1.0/字体部分/8x8.FON

    8x8 : 8178 glyphs x 8 B, glyph = GB2312 index (hi-0xA1)*94 + (lo-0xA1),
          column-major, one page, one bit per row, LSB first.

Which characters go in: every CJK character in a string literal of the
sources below, plus every character listed in app/cn_chars.txt.

    python tools/mkcnfont.py            # regenerate app/cn_font.c
    python tools/mkcnfont.py --list     # print the character set and sizes
    python tools/mkcnfont.py --check    # fail when cn_font.c is out of date

The generated file is committed, so the build needs neither Python nor the
.FON file.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

FON8 = os.path.join(ROOT, "tools", "font", "8x8.FON")
EXTRA = os.path.join(ROOT, "app", "cn_chars.txt")
OUT = os.path.join(ROOT, "app", "cn_font.c")
OUT_H = os.path.join(ROOT, "app", "cn_font.h")

GLYPH8 = 8
GLYPH_COUNT = 94 * 87          # GB2312 0xA1A1 .. 0xF7FE

# Source files whose string literals are scanned. Only CJK is taken, so the
# English literals next to them cost nothing.
SOURCES = [
    "app/tdcs.c",
]


def gb_index(ch):
    try:
        b = ch.encode("gb2312")
    except UnicodeEncodeError:
        return None
    if len(b) != 2:
        return None
    hi, lo = b[0], b[1]
    if not (0xA1 <= hi <= 0xF7 and 0xA1 <= lo <= 0xFE):
        return None
    return (hi - 0xA1) * 94 + (lo - 0xA1)


def load_font(path, size):
    with open(path, "rb") as f:
        data = f.read()
    need = GLYPH_COUNT * size
    if len(data) < need:
        sys.exit("%s: %d bytes, need at least %d" % (path, len(data), need))
    return data


def is_cjk(ch):
    o = ord(ch)
    return (0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF
            or 0x3000 <= o <= 0x303F or 0xFF00 <= o <= 0xFFEF)


STR_RE = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def scan_sources(files):
    chars = set()
    for rel in files:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        for line in text.splitlines():
            line = line.split("//", 1)[0]
            for m in STR_RE.finditer(line):
                for ch in m.group(1):
                    if is_cjk(ch) and gb_index(ch) is not None:
                        chars.add(ch)
    return chars


def scan_extra():
    chars = set()
    if not os.path.exists(EXTRA):
        return chars
    with open(EXTRA, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0]
            for ch in line:
                if is_cjk(ch) and gb_index(ch) is not None:
                    chars.add(ch)
    return chars


def build():
    f8 = load_font(FON8, GLYPH8)
    chars = scan_sources(SOURCES) | scan_extra()

    out = []
    for ch in chars:
        idx = gb_index(ch)
        out.append((idx, ch, f8[idx * GLYPH8:(idx + 1) * GLYPH8]))
    out.sort(key=lambda e: e[0])
    return out


def indent(data, per_line=16, width=2):
    out = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        out.append("    " + ", ".join("0x%0*x" % (width, b) for b in chunk) + ",")
    return "\n".join(out)


HEADER = """\
/* Generated by tools/mkcnfont.py - do not edit by hand.
 *
 * The Chinese characters the TDCS popup draws, cut out of the FontTool
 * 8x8 dot-matrix file (tools/font/8x8.FON). The classic UV-K5 has no
 * external font flash, so the glyphs are carried inside the firmware image:
 *
 *    8x8 : 8 B, column-major, one page
 *
 * Sorted by GB2312 index, binary searched. A raw GB2312 pair that is not in
 * the set has no glyph here; the drawing code then leaves a blank cell.
 */
#ifndef APP_CN_FONT_H
#define APP_CN_FONT_H

#include <stdbool.h>
#include <stdint.h>

#define CN_FONT_GLYPH8    8u

/* Number of 8x8 characters carried in the image. */
#define CN_FONT_COUNT8    %(n8)du

/* Null when the character is not in the built-in set. */
const uint8_t *CN_FONT_Glyph8(uint16_t code);

#endif /* APP_CN_FONT_H */
"""


def emit(entries, out_c=None, out_h=None):
    out_c = out_c or OUT
    out_h = out_h or OUT_H

    with open(out_h, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER % {"n8": len(entries)})

    with open(out_c, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/mkcnfont.py - do not edit by hand. */\n")
        f.write('#include "cn_font.h"\n\n')

        f.write("static const uint16_t cnCodes8[CN_FONT_COUNT8] = {\n")
        line = []
        for e in entries:
            line.append("0x%04X," % e[0])
            if len(line) == 12:
                f.write("    " + " ".join(line) + "\n")
                line = []
        if line:
            f.write("    " + " ".join(line) + "\n")
        f.write("};\n\n")

        f.write("static const uint8_t cnGlyph8[CN_FONT_COUNT8 * %d] =\n{\n"
                % GLYPH8)
        f.write("\n".join(indent(e[2]) for e in entries) + "\n};\n\n")

        f.write("""\
/* Index of a GB2312 code in the sorted table, or n when it is not there. */
static uint16_t cn_find(uint16_t n, uint16_t code){
    uint16_t lo = 0u, hi = n;
    while (lo < hi){
        const uint16_t mid = (uint16_t)(lo + (uint16_t)((hi - lo) >> 1));
        const uint16_t c = cnCodes8[mid];
        if (c == code) return mid;
        if (c < code) lo = (uint16_t)(mid + 1u); else hi = mid;
    }
    return n;
}

/* The tables are sorted by the GB2312 index, but the drawing code hands over
 * the raw GB2312 pair. A byte outside the GB2312 range has no glyph. */
static uint16_t cn_index(uint16_t code){
    const uint8_t hi = (uint8_t)(code >> 8);
    const uint8_t lo = (uint8_t)code;
    if (hi < 0xA1u || hi > 0xF7u || lo < 0xA1u || lo > 0xFEu)
        return 0xFFFFu;
    return (uint16_t)((uint16_t)(hi - 0xA1u) * 94u + (lo - 0xA1u));
}

const uint8_t *CN_FONT_Glyph8(uint16_t code){
    const uint16_t i = cn_find(CN_FONT_COUNT8, cn_index(code));
    return (i < CN_FONT_COUNT8) ? &cnGlyph8[(uint32_t)i * CN_FONT_GLYPH8] : 0;
}
""")


def main():
    ap = argparse.ArgumentParser(description="Build the built-in Chinese font subset")
    ap.add_argument("--list", action="store_true", help="print the character set")
    ap.add_argument("--check", action="store_true",
                    help="fail unless app/cn_font.c is up to date")
    args = ap.parse_args()

    entries = build()
    n8 = len(entries)
    size8 = n8 * GLYPH8

    if args.list:
        print("8x8: %d chars %d B" % (n8, size8))
        print("chars: " + "".join(e[1] for e in entries))
        return 0

    if args.check:
        if not os.path.exists(OUT) or not os.path.exists(OUT_H):
            sys.exit("app/cn_font.c is missing, run tools/mkcnfont.py")
        import tempfile
        tmp = tempfile.mkdtemp()
        a_c = os.path.join(tmp, "cn_font.c")
        a_h = os.path.join(tmp, "cn_font.h")
        emit(entries, a_c, a_h)

        def norm(path):
            with open(path, "rb") as f:
                return f.read().replace(b"\r\n", b"\n")
        same = (norm(a_c) == norm(OUT) and norm(a_h) == norm(OUT_H))
        if not same:
            sys.exit("app/cn_font.c is out of date, run tools/mkcnfont.py")
        print("cn_font.c is up to date (%d chars)" % n8)
        return 0

    emit(entries)
    print("wrote app/cn_font.c: 8x8 %d chars %d B" % (n8, size8))
    return 0


if __name__ == "__main__":
    sys.exit(main())
